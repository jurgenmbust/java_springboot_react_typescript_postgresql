-- Flyway owns the schema. Hibernate only validates it.
CREATE TABLE categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL CHECK (length(trim(name)) > 0),
 description VARCHAR(1000) NOT NULL DEFAULT '',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uk_category_name ON categories (lower(name));
CREATE TABLE products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL CHECK (length(trim(name)) > 0),
 description VARCHAR(2000) NOT NULL DEFAULT '',
 sku VARCHAR(64) NOT NULL UNIQUE CHECK (sku ~ '^[A-Z0-9_-]+$'),
 price NUMERIC(14,2) NOT NULL CHECK (price >= 0),
 quantity INTEGER NOT NULL CHECK (quantity >= 0),
 category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_product_category ON products(category_id);
CREATE INDEX ix_product_name ON products(lower(name));
CREATE INDEX ix_product_created ON products(created_at DESC);
CREATE INDEX ix_product_price ON products(price);
CREATE INDEX ix_product_quantity ON products(quantity);
